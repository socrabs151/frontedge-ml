"""Генератор TypeScript-типов из pydantic-моделей.

Чистый Python: `pip install frontedge` не требует Node. Генератор читает JSON Schema
модели и дополнительно вытаскивает роли `x-frontedge`, чтобы фронт знал, как показывать
поле: метрику, статус, timestamp, идентификатор.
"""

from __future__ import annotations

import json
from typing import Any

from pydantic import BaseModel

__all__ = ["generate_client", "generate_types", "roles_of", "schema_of"]


def schema_of(models: list[type[BaseModel]]) -> tuple[dict[str, Any], dict[str, dict[str, str]]]:
    """Схема и карта ролей по всем моделям."""
    schema: dict[str, Any] = {"$defs": {}}
    roles: dict[str, dict[str, str]] = {}

    for model in models:
        model_schema = model.model_json_schema(ref_template="#/$defs/{model}")
        schema["$defs"].update(model_schema.get("$defs", {}))
        schema["$defs"][model.__name__] = {
            key: value
            for key, value in model_schema.items()
            if key not in {"$defs", "title"}
        }
        roles[model.__name__] = roles_of(model_schema)

    return schema, roles


def roles_of(model_schema: dict[str, Any]) -> dict[str, str]:
    """Роли `x-frontedge` полей модели."""
    found: dict[str, str] = {}
    for name, prop in model_schema.get("properties", {}).items():
        extra = prop.get("x-frontedge")
        if isinstance(extra, dict) and "role" in extra:
            found[name] = str(extra["role"])
    return found


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def _ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return _ref_name(schema["$ref"])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = [_ts_type(sub) for sub in schema[key]]
            unique: list[str] = []
            for part in parts:
                if part not in unique:
                    unique.append(part)
            return " | ".join(unique)
    if "allOf" in schema and len(schema["allOf"]) == 1:
        return _ts_type(schema["allOf"][0])

    kind = schema.get("type")
    if kind == "object" or ("properties" in schema and kind is None):
        properties = schema.get("properties")
        if properties:
            required = set(schema.get("required", []))
            fields = []
            for name, prop in properties.items():
                optional = "" if name in required else "?"
                fields.append(f"{name}{optional}: {_ts_type(prop)};")
            return "{ " + " ".join(fields) + " }"
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            return f"Record<string, {_ts_type(additional)}>"
        return "Record<string, unknown>"
    if kind == "array":
        item = _ts_type(schema.get("items", {}))
        if " | " in item:
            item = f"({item})"
        return f"{item}[]"
    if kind == "string":
        return "string"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    return "unknown"


def _interface(name: str, schema: dict[str, Any]) -> str:
    properties = schema.get("properties", {})
    required = set(schema.get("required", []))
    if not properties:
        return f"export type {name} = {_ts_type(schema)};"
    lines = []
    for field, prop in properties.items():
        optional = "" if field in required else "?"
        lines.append(f"  {field}{optional}: {_ts_type(prop)};")
    body = "\n".join(lines)
    return f"export interface {name} {{\n{body}\n}}"


def generate_types(models: list[type[BaseModel]], *, header: str = "") -> str:
    """Файл `types.ts`: интерфейсы, типы и карта ролей."""
    schema, roles = schema_of(models)
    defs = schema["$defs"]

    blocks: list[str] = []
    for name, definition in defs.items():
        if "$ref" in definition:
            continue
        blocks.append(_interface(name, definition))

    role_lines = []
    for model_name, model_roles in roles.items():
        for field, role_name in model_roles.items():
            key = json.dumps(f"{model_name}.{field}", ensure_ascii=False)
            role_lines.append(f"  {key}: {json.dumps(role_name, ensure_ascii=False)},")
    roles_block = (
        "export const frontedgeRoles = {\n" + "\n".join(role_lines) + "\n} as const;\n"
        if role_lines
        else "export const frontedgeRoles = {} as const;\n"
    )

    parts = [
        header or "// Generated by frontedge. Do not edit by hand.",
        "",
        *blocks,
        "",
        roles_block,
    ]
    return "\n".join(parts)


def generate_client(*, base_path: str = "/frontedge/api") -> str:
    """Файл `client.ts`: типизированный клиент к API Frontedge."""
    return f'''// Generated by frontedge. Do not edit by hand.
import type {{
  ActionResult,
  Artifact,
  DatasetDetail,
  DatasetInfo,
  EvalComparison,
  EvalSummary,
  LogLine,
  Run,
  UiConfig,
}} from "./types";

export interface FrontedgeClientOptions {{
  basePath?: string;
  fetch?: typeof globalThis.fetch;
}}

export interface FrontedgeMeta {{
  name: string;
  version: string;
  statuses: string[];
  freshness: string[];
  metricDirections: string[];
}}

export function createClient(options: FrontedgeClientOptions = {{
}}) {{
  const basePath = options.basePath ?? "{base_path}";
  const doFetch = options.fetch ?? globalThis.fetch.bind(globalThis);

  async function json<T>(path: string): Promise<T> {{
    const response = await doFetch(`${{basePath}}${{path}}`, {{
      headers: {{ accept: "application/json" }},
    }});
    if (!response.ok) {{
      throw new Error(`frontedge: ${{response.status}} ${{response.statusText}} (${{path}})`);
    }}
    return (await response.json()) as T;
  }}

  async function send<T>(path: string, payload: unknown): Promise<T> {{
    const response = await doFetch(`${{basePath}}${{path}}`, {{
      method: "POST",
      headers: {{ accept: "application/json", "content-type": "application/json" }},
      body: JSON.stringify(payload),
    }});
    if (!response.ok) {{
      throw new Error(`frontedge: ${{response.status}} ${{response.statusText}} (${{path}})`);
    }}
    return (await response.json()) as T;
  }}

  return {{
    listRuns: () => json<Run[]>("/runs"),
    getRun: (runId: string) => json<Run>(`/runs/${{runId}}`),
    listEvals: () => json<EvalSummary[]>("/evals"),
    compareEval: (evalId: string, reference: string, comparison: string) =>
      json<EvalComparison>(
        `/evals/${{encodeURIComponent(evalId)}}/compare?reference=${{encodeURIComponent(reference)}}&comparison=${{encodeURIComponent(comparison)}}`,
      ),
    listDatasets: () => json<DatasetInfo[]>("/datasets"),
    getDataset: (datasetId: string) =>
      json<DatasetDetail>(`/datasets/${{encodeURIComponent(datasetId)}}`),
    config: () => json<UiConfig>("/config"),
    runAction: (actionId: string, payload: Record<string, unknown> = {{}}) =>
      send<ActionResult>(`/actions/${{encodeURIComponent(actionId)}}`, payload),
    meta: () => json<FrontedgeMeta>("/meta"),
    async *streamLogs(runId: string): AsyncGenerator<LogLine> {{
      const response = await doFetch(`${{basePath}}/runs/${{runId}}/logs/stream`, {{
        headers: {{ accept: "text/event-stream" }},
      }});
      if (!response.ok || !response.body) {{
        throw new Error(`frontedge: не удалось открыть поток логов (${{runId}})`);
      }}
      const reader = response.body.getReader();
      const decoder = new TextDecoder();
      let buffer = "";
      while (true) {{
        const {{ done, value }} = await reader.read();
        if (done) break;
        buffer += decoder.decode(value, {{ stream: true }});
        const chunks = buffer.split("\\n\\n");
        buffer = chunks.pop() ?? "";
        for (const chunk of chunks) {{
          const dataLine = chunk.split("\\n").find((line) => line.startsWith("data:"));
          if (!dataLine) continue;
          yield JSON.parse(dataLine.slice(5).trim()) as LogLine;
        }}
      }}
    }},
  }};
}}

export type {{
  ActionResult,
  Artifact,
  DatasetDetail,
  DatasetInfo,
  EvalComparison,
  EvalSummary,
  LogLine,
  Run,
  UiConfig,
}};
'''
